using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace Wayfinder.TypeGen;

/// <summary>
/// Writes the TypeScript declarations matching how C# types are written on the wire. Each root
/// is added with the <see cref="WireContract"/> it travels by (a blueprint as YAML, an API result
/// as JSON), and every type it reaches is described by that same contract, so the TypeScript says
/// exactly what the wire says. A property is optional when a reader can find it missing.
/// </summary>
public sealed class TypeScriptEmitter
{
    private readonly SortedDictionary<string, string> _declarations = new(StringComparer.Ordinal);
    private readonly Dictionary<string, Type> _namedTypes = new(StringComparer.Ordinal);
    private readonly Queue<(Type Type, WireContract Contract)> _pending = new();
    private readonly SortedDictionary<string, string> _keyOrders = new(StringComparer.Ordinal);
    private readonly SortedDictionary<string, string> _discriminators = new(StringComparer.Ordinal);

    public TypeScriptEmitter Add(WireContract contract, params Type[] roots)
    {
        foreach (var root in roots)
        {
            Reference(root, contract);
        }

        while (_pending.TryDequeue(out var next))
        {
            Declare(next.Type, next.Contract);
        }

        return this;
    }

    public string Render()
    {
        var output = new StringBuilder();
        output.Append("// <auto-generated>\n");
        output.Append("// Generated from the C# model by Wayfinder.TypeGen. Do not edit by hand:\n");
        output.Append("//   dotnet run --project Wayfinder.TypeGen -- write <this file>\n");
        output.Append("// </auto-generated>\n\n");
        output.Append(string.Join("\n", _declarations.Values));
        if (_keyOrders.Count > 0)
        {
            output.Append("\n/** The order each type's keys are written in, and the named type of each nested value or map entry. */\n");
            output.Append("export const yamlShapes: Record<string, YamlShape> = {\n");
            output.Append(string.Concat(_keyOrders.Values));
            output.Append("};\n\n/** For each polymorphic type, the key that names the concrete type and the type each value names. */\n");
            output.Append("export const yamlDiscriminators: Record<string, { property: string; types: Record<string, string> }> = {\n");
            output.Append(string.Concat(_discriminators.Values));
            output.Append("};\n\nexport interface YamlShape {\n  keys: readonly string[];\n  nested: Record<string, string>;\n  maps: Record<string, string>;\n}\n");
        }

        return output.ToString();
    }

    /// <summary>The TypeScript expression for a type, queuing a declaration for any named type it needs.</summary>
    private string Reference(Type type, WireContract contract)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;

        if (Primitive(type) is { } primitive)
        {
            return primitive;
        }

        var (kind, element) = contract.Classify(type);
        if (kind == WireKind.Map)
        {
            return $"Record<string, {Reference(element!, contract)}>";
        }

        if (kind == WireKind.List)
        {
            var reference = Reference(element!, contract);
            return reference.Contains(' ', StringComparison.Ordinal) ? $"({reference})[]" : $"{reference}[]";
        }

        return Name(type, contract);
    }

    private static string? Primitive(Type type)
    {
        if (type == typeof(string) || type == typeof(Guid) || type == typeof(DateTime)
            || type == typeof(DateTimeOffset) || type == typeof(TimeSpan) || type == typeof(Uri))
        {
            return "string";
        }

        if (type == typeof(bool))
        {
            return "boolean";
        }

        if (type == typeof(JsonObject))
        {
            return "Record<string, unknown>";
        }

        if (type == typeof(JsonArray))
        {
            return "unknown[]";
        }

        if (type == typeof(object) || type == typeof(JsonNode) || type == typeof(JsonElement))
        {
            return "unknown";
        }

        return type.IsPrimitive || type == typeof(decimal) ? "number" : null;
    }

    private string Name(Type type, WireContract contract)
    {
        if (_namedTypes.TryGetValue(type.Name, out var existing))
        {
            return existing == type
                ? type.Name
                : throw new InvalidOperationException($"Two C# types are both named {type.Name}: {existing.FullName} and {type.FullName}.");
        }

        _namedTypes[type.Name] = type;
        _pending.Enqueue((type, contract));
        return type.Name;
    }

    private void Declare(Type type, WireContract contract)
    {
        _declarations[type.Name] = type.IsEnum
            ? DeclareEnum(type, contract)
            : contract.Polymorphism(type) is { } polymorphism
                ? DeclarePolymorphic(type, polymorphism, contract)
                : DeclareInterface(type.Name, contract.Members(type), contract, discriminator: null);
    }

    private static string DeclareEnum(Type type, WireContract contract)
    {
        var values = string.Join(", ", Enum.GetValues(type).Cast<object>().Select(value => $"'{contract.EnumValue(type, value)}'"));
        var constant = char.ToLowerInvariant(type.Name[0]) + type.Name[1..] + "Values";
        return $"export const {constant} = [{values}] as const;\nexport type {type.Name} = (typeof {constant})[number];\n";
    }

    private string DeclarePolymorphic(Type baseType, WirePolymorphism polymorphism, WireContract contract)
    {
        var members = new List<string>();
        var declarations = new StringBuilder();
        foreach (var (derived, discriminator) in polymorphism.DerivedTypes)
        {
            declarations.Append(DeclareInterface(derived.Name, contract.Members(derived), contract, (polymorphism.DiscriminatorProperty, discriminator)));
            members.Add(derived.Name);
        }

        declarations.Append(CultureInfo.InvariantCulture, $"export type {baseType.Name} =\n  | {string.Join("\n  | ", members)};\n");
        if (contract.OrdersKeys)
        {
            var types = string.Join(", ", polymorphism.DerivedTypes.Select(derived => $"{Key(derived.Discriminator)}: '{derived.Type.Name}'"));
            _discriminators[baseType.Name] = $"  {baseType.Name}: {{ property: '{polymorphism.DiscriminatorProperty}', types: {{ {types} }} }},\n";
        }

        return declarations.ToString();
    }

    private string DeclareInterface(
        string name, IReadOnlyList<WireMember> members, WireContract contract, (string Property, string Value)? discriminator)
    {
        var body = new StringBuilder();
        if (discriminator is var (property, value))
        {
            body.Append(CultureInfo.InvariantCulture, $"  {property}: '{value}';\n");
        }

        foreach (var member in members)
        {
            var tsType = member.TypeScript ?? Reference(member.Type, contract);
            body.Append(CultureInfo.InvariantCulture, $"  {Key(member.Name)}{(member.Optional ? "?" : "")}: {tsType};\n");
        }

        if (contract.OrdersKeys)
        {
            RecordKeyOrder(name, members, contract, discriminator?.Property);
        }

        return $"export interface {name} {{\n{body}}}\n";
    }

    private void RecordKeyOrder(string name, IReadOnlyList<WireMember> members, WireContract contract, string? discriminator)
    {
        var keys = (discriminator is null ? [] : new[] { discriminator }).Concat(members.Select(member => member.Name));
        var nested = new List<string>();
        var maps = new List<string>();
        foreach (var member in members)
        {
            if (NamedElement(member.Type, contract, out var isMap) is { } element)
            {
                (isMap ? maps : nested).Add($"{Key(member.Name)}: '{element}'");
            }
        }

        _keyOrders[name] = $"  {name}: {{ keys: [{string.Join(", ", keys.Select(key => $"'{key}'"))}], " +
            $"nested: {Literal(nested)}, maps: {Literal(maps)} }},\n";
    }

    private static string Literal(List<string> entries) => entries.Count == 0 ? "{}" : $"{{ {string.Join(", ", entries)} }}";

    /// <summary>The named type a value holds, looking through lists and (setting <paramref name="isMap"/>) maps; null for plain values.</summary>
    private static string? NamedElement(Type type, WireContract contract, out bool isMap)
    {
        isMap = false;
        type = Nullable.GetUnderlyingType(type) ?? type;
        while (Primitive(type) is null && !type.IsEnum)
        {
            var (kind, element) = contract.Classify(type);
            if (kind == WireKind.Structure)
            {
                return type.Name;
            }

            isMap |= kind == WireKind.Map;
            type = Nullable.GetUnderlyingType(element!) ?? element!;
        }

        return null;
    }

    private static string Key(string name) =>
        name.All(c => char.IsLetterOrDigit(c) || c == '_') && !char.IsDigit(name[0]) ? name : $"'{name}'";
}
